"""Порча расшифровки: петли ASR и потерянная речь — одним детектором.

ASR на тишине и на плохом звуке не молчит, а **зацикливается**: выдаёт серию одной буквы, повтор
слова, ряд знаков. Речь, которая в это время звучала, теряется молча — и до сих пор её терял
каждый прогон, потому что единственный датчик искал ПОВТОР ФРАЗЫ (слова от двух знаков через
пробел, четыре раза подряд) и три самые частые формы не видел вовсе:

    «ИИИИИИИИИИ»          — один токен без пробелов;
    «!!!!!!!!»            — не буквы;
    «И И И И И»           — слова из одного знака;
    «да-да-да-да-да»      — дефисы делают это одним токеном;
    «СловоСловоСлово»     — повтор внутри токена.

⚠️⚠️ **Пороги ниже ИЗМЕРЕНЫ по корпусу в 193 записи (1.44 млн слов), а не назначены.** Это важно:
прежний датчик с «долей уникальных слов» объявлял мусором треть корпуса, потому что порог взяли
из головы. Распределения — в `docs/asr-runs.md`; здесь у каждой формы своё обоснование.

Шестая форма стоит отдельно (`scan_holes`): **дыра во времени внутри реплики** — реплика это
непрерывная речь по диаризатору, а слов на отрезке нет ни одного, значит расшифровка их потеряла.
Текста тут нет вовсе, поэтому формы `scan_text`/`scan_word` на неё слепы по устройству. Дыра бывает
и между границей реплики и первым (последним) словом — такие считаются тоже, иначе теряется больше
трети находок.
⚠️ Урожай у этой формы низкий и это замер: диаризатор клеит отрезки речи через паузы, поэтому
«дыра» чаще всего и есть пауза (измерено на одном корпусе: настоящая речь в 3 % дыр). Форма нужна,
чтобы ЗНАТЬ, где речь потеряна, а не чтобы чинить оптом.

⚠️ Детектор НИЧЕГО не чинит и не выбрасывает — он возвращает СПАНЫ (что, где, сколько). Решение
принимает тот, кто умеет переслушать звук: схлопнуть повтор значит спрятать след, а речь, съеденную
петлёй, этим не вернуть.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# --- пороги, каждый со своим замером ---------------------------------------------------------

# Серия одного символа внутри слова. Замер: длина 3 — 89 случаев (нормальные «ааа», «ооо»),
# 4-7 — 16, а на 8-9 в корпусе ПУСТО, дальше 31 случай длиной 10-221. Разрыв чистый.
CHAR_RUN = 8

# Серия знаков. Замер: 3 — 1587 случаев (это многоточие), 4 — два, и до 14 пусто. Берём 5, чтобы
# не трогать законное «!!!» и «...» и при этом ловить «!!!!!!!!» из жалобы.
PUNCT_RUN = 5

# Повтор подстроки внутри одного токена («СловоСловоСлово»). Замер: 2 повтора — 23 случая (среди
# них законные слова), 3 и больше — 8 случаев, все петли.
TOKEN_REPEAT = 3

# Повтор слова подряд БЕЗ учёта времени. Замер: 3 повтора — 545 случаев (обычная речь: «да, да,
# да»), 4-7 — 82, и только от 8 начинается то, чего в речи не бывает: «А, А, А…» ×112, «0, 0,
# 0…» ×108, «а а а…» ×24.
WORD_RUN = 8

# Повтор слова С учётом времени: три повтора, растянутые на секунды. Замер по пословным временам:
# короче 3 с — 246 случаев, и все до одного нормальная речь («Кузнецова, Кузнецова, Кузнецова» —
# полторы секунды: человек зовёт коллегу);
# от 6 с — 31 случай, и там «Извание Извание Извание» на 115 секундах.
WORD_RUN_SEC = 3
RUN_SEC = 6.0

# Одно слово, растянутое во времени. Пословные времена ставит выравнивание: если слово занимает
# десять секунд, значит выравнивателю нечего было положить в этот кусок — расшифровка ПОТЕРЯЛА
# речь. Замер: из 1 436 820 слов дольше 5 с — 329 (0.02 %), дольше 10 с — 86; в хвосте «Полюбим.»
# на 41 с и «Привет.» на 23 с. Это не петля, но место, где надо переслушать.
WORD_SEC = 5.0

# Дыра во времени ВНУТРИ реплики. Реплика — непрерывная речь по диаризатору: он слышал голос, а
# слов на этом отрезке нет ни одного, значит расшифровка речь потеряла. Порог тот же, что у
# разреженной речи в стадии переслушивания (8 с).
# ⚠️ Дыра МЕЖДУ репликами — законная тишина (диаризатор там речи и не слышал), поэтому считаем
# только внутри. Замерено по корпусу в 193 записи: дыр ≥ 8 с между репликами 2255 на 15 часов,
# и в топе практические занятия курса, где преподаватель молчит; внутри реплик — 1102 дыры на
# 5 часов, и проба 12 дыр из четырёх веток дала речь в 12 из 12.
HOLE_SEC = 8.0

_CHAR = re.compile(rf"([^\W\d_])\1{{{CHAR_RUN - 1},}}", re.U)
_PUNCT = re.compile(rf"([!?.,…])\1{{{PUNCT_RUN - 1},}}")
_TOKEN = re.compile(rf"\b([^\W\d_]{{2,15}}?)\1{{{TOKEN_REPEAT - 1},}}\b", re.U)
# ⚠️ Формы не должны ловить ОДНО И ТО ЖЕ место дважды: «ИИИИИИИИ» — это серия символа, а не
# повтор подстроки «ИИ», и «нет нет нет нет» — повтор слова, а не фразы. Иначе одно место уедет
# на переслушивание тремя спанами, и три ответа потом не с чем сводить.
_WORD = re.compile(r"[^\W\d_]+", re.U)
# Повтор фразы — прежний датчик приёмки, оставлен как шестая форма: он ловит то, что не ловят
# остальные («не знаю не знаю не знаю»), и его порог уже обоснован замером 2026-09.
_PHRASE = re.compile(r"\b([\w'-]{2,}(?:\s+[\w'-]{2,}){1,3})(?:[,.!?…]?\s+\1\b){3,}", re.I | re.U)

KINDS = ("char", "punct", "token", "word", "run", "long", "phrase")


@dataclass
class Span:
    """Место порчи: что нашли, где и сколько. Времена — если их дали (пословный сайдкар)."""

    kind: str                     # одна из KINDS
    sample: str                   # короткий образец — чтобы человек узнал место
    n: int = 0                    # сколько повторов/знаков
    t0: float | None = None
    t1: float | None = None
    turn: int | None = None       # номер реплики, если известен
    extra: dict = field(default_factory=dict)

    @property
    def sec(self) -> float:
        return 0.0 if self.t0 is None or self.t1 is None else round(self.t1 - self.t0, 1)

    def line(self) -> str:
        at = f"{int(self.t0 // 60)}:{int(self.t0 % 60):02d}" if self.t0 is not None else "—"
        return f"{self.kind:>6} ×{self.n:<4} {at:>7} {self.sec:>5} с  {self.sample[:44]!r}"


def scan_word(word: str) -> list[Span]:
    """Формы, которые целиком помещаются в ОДНО слово: серия символа, знаки, повтор подстроки.

    ⚠️ Проверять их по слову, а не по тексту реплики, — не педантизм: у спана должно быть ТОЧНОЕ
    время. Поиск по склеенному тексту давал спан длиной во всю реплику (17 минут вместо 25 с), и
    переслушивать такой кусок бессмысленно.
    """
    out: list[Span] = []
    for m in _CHAR.finditer(word):
        out.append(Span("char", m.group(0)[:40], len(m.group(0))))
    for m in _PUNCT.finditer(word):
        out.append(Span("punct", m.group(0)[:40], len(m.group(0))))
    for m in _TOKEN.finditer(word):
        if len(set(m.group(1))) < 2:
            continue                      # «ИИИИ» — это серия символа, её ловит форма выше
        out.append(Span("token", m.group(0)[:40], len(m.group(0)) // max(1, len(m.group(1)))))
    return out


def scan_text(text: str) -> list[Span]:
    """Формы, которые видны в самом тексте, без времён."""
    out: list[Span] = []
    for word in text.split():
        out += scan_word(word)
    for m in _PHRASE.finditer(text):
        out.append(Span("phrase", m.group(0)[:60], len(_WORD.findall(m.group(0)))))
    # Повтор слова подряд — считаем по словам, а не регэкспом: дефисные сцепки («да-да-да»)
    # регэксп видит одним токеном, и повтор внутри него не замечает вовсе.
    words = _WORD.findall(text)
    for i, j, key in _runs(words):
        n = j - i + 1
        if n >= WORD_RUN:
            out.append(Span("word", " ".join([key] * min(n, 5)), n))
    return out


def scan_words(turns: list[dict]) -> list[Span]:
    """Формы, для которых нужно ВРЕМЯ: растянутый повтор и растянутое слово.

    `turns` — реплики пословного сайдкара (`record.words.json::turns`), слово — `[текст, t0, t1]`
    либо `{w, t0, t1}`. Формы из `scan_text` тоже проверяются — по тексту реплики, чтобы у спана
    было время.
    """
    out: list[Span] = []
    for idx, turn in enumerate(turns):
        items = [_word(w) for w in (turn.get("words") or [])]
        items = [w for w in items if w[0]]
        if not items:
            continue
        for word, t0, t1 in items:
            for span in scan_word(word):
                span.turn, span.t0, span.t1 = idx, t0, t1
                out.append(span)
        text = " ".join(w[0] for w in items)
        for m in _PHRASE.finditer(text):
            span = Span("phrase", m.group(0)[:60], len(_WORD.findall(m.group(0))), turn=idx)
            span.t0, span.t1 = _where(items, span)
            out.append(span)
        keys = [_key(w[0]) for w in items]
        for i, j, key in _runs(keys):
            n = j - i + 1
            t0, t1 = items[i][1], items[j][2]
            if n >= WORD_RUN_SEC and t1 - t0 >= RUN_SEC and n < WORD_RUN:
                out.append(Span("run", " ".join([items[i][0]] * min(n, 4)), n, t0, t1, idx))
        for word, t0, t1 in items:
            if t1 - t0 >= WORD_SEC:
                out.append(Span("long", word[:40], 1, t0, t1, idx))
    return out


def scan_holes(turns: list[dict]) -> list[Span]:
    """Дыры во времени внутри реплик: место есть, речи в расшифровке нет.

    Отдельной функцией, а не формой в `scan_words`, по двум причинам. Во-первых, это порча ДРУГОГО
    рода: там текст сломан и виден глазом, здесь текста нет вовсе, и в отчётах их надо считать
    порознь. Во-вторых, у дыры нет «образца»: `sample` описывает соседей, а не саму порчу.
    """
    out: list[Span] = []
    for idx, turn in enumerate(turns):
        items = [_word(w) for w in (turn.get("words") or [])]
        items = [w for w in items if w[0]]
        if not items:
            continue                             # реплика без слов вовсе — не дыра, а пустая запись
        items.sort(key=lambda w: w[1])
        for (w0, _, b0), (w1, a1, _) in zip(items, items[1:]):
            if a1 - b0 >= HOLE_SEC:
                out.append(Span("hole", f"{w0} ⟨…⟩ {w1}"[:60], 0, b0, a1, idx))
        # ⚠️ Дыра бывает и НА КРАЮ реплики: диаризатор слышит речь с 10-й секунды, а первое слово
        # стоит на 20-й. Между словами такого провала нет вовсе, и без этих двух проверок он
        # невидим — ловилось на записи, с которой начался весь разбор: 10 секунд речи о том,
        # почему доклад так называется, не было ни в тексте, ни в списке подозрительных мест.
        start, end = turn.get("start"), turn.get("end")
        if start is not None and items[0][1] - float(start) >= HOLE_SEC:
            out.append(Span("hole", f"⟨…⟩ {items[0][0]}"[:60], 0, float(start), items[0][1], idx))
        if end is not None and float(end) - items[-1][2] >= HOLE_SEC:
            out.append(Span("hole", f"{items[-1][0]} ⟨…⟩"[:60], 0, items[-1][2], float(end), idx))
    return out


def merge(spans: list[Span], gap: float = 1.0) -> list[Span]:
    """Слить пересекающиеся спаны: одно и то же место часто ловится двумя формами сразу.

    ⚠️ Переслушивать надо МЕСТО, а не каждую форму по отдельности — иначе один кусок уедет в
    модель трижды, а три разных ответа потом не с чем будет сводить.
    """
    timed = sorted([s for s in spans if s.t0 is not None], key=lambda s: (s.t0, s.t1 or s.t0))
    out: list[Span] = []
    for s in timed:
        if out and s.t0 - (out[-1].t1 or out[-1].t0) <= gap:
            prev = out[-1]
            prev.t1 = max(prev.t1 or prev.t0, s.t1 or s.t0)
            prev.n = max(prev.n, s.n)
            prev.extra.setdefault("kinds", {prev.kind})
            prev.extra["kinds"].add(s.kind)
            if len(s.sample) > len(prev.sample):
                prev.sample = s.sample
        else:
            out.append(s)
    return out + [s for s in spans if s.t0 is None]


# --- мелочь ----------------------------------------------------------------------------------

def _word(w) -> tuple[str, float, float]:
    if isinstance(w, (list, tuple)):
        return (str(w[0] or ""), float(w[1]), float(w[2]))
    return (str(w.get("w") or ""), float(w.get("t0", 0.0)), float(w.get("t1", 0.0)))


def _key(word: str) -> str:
    return word.lower().strip(".,!?…:;—-«»\"'()")


def _runs(items: list[str]):
    """Подряд идущие одинаковые элементы: (начало, конец, значение), только группы от трёх."""
    i = 0
    while i < len(items):
        j = i
        while j + 1 < len(items) and items[j + 1] == items[i] and items[i]:
            j += 1
        if j - i + 1 >= 3 and items[i]:
            yield i, j, items[i]
        i = j + 1


def _where(items: list[tuple[str, float, float]], span: Span) -> tuple[float | None, float | None]:
    """Время повтора ФРАЗЫ: от первого слова, с которого он начинается, до конца повтора.

    ⚠️ Не нашли начала — время берём не от всей реплики (она бывает в двадцать минут), а не даём
    вовсе: спан без времени честнее спана, который зовёт переслушать полчаса.
    """
    head = _key(span.sample.split()[0]) if span.sample.split() else ""
    words = span.sample.split()
    for k, (word, t0, _t1) in enumerate(items):
        if head and _key(word) == head:
            last = min(k + len(words) - 1, len(items) - 1)
            return t0, items[last][2]
    return None, None
