"""Детектор порчи расшифровки: ловит петли ASR и потерянную речь, но не трогает живую речь.

⚠️ Пороги здесь не «красивые числа», а замер по корпусу в 193 записи — обоснование каждого стоит
в `tools/degenerate.py`. Тест закрепляет ОБЕ стороны: что ловится и что НЕ ловится. Вторая сторона
важнее: датчик, который кричит на «да, да, да», выключат в первую же неделю.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import degenerate as dg  # noqa: E402


def kinds(spans) -> set[str]:
    return {s.kind for s in spans}


def turn(words, t0=0.0, step=0.4):
    """Реплика пословного сайдкара: слова подряд по `step` секунд."""
    out, t = [], t0
    for w in words:
        out.append([w, round(t, 2), round(t + step, 2)])
        t += step
    return {"words": out}


# --- что ЛОВИТСЯ -----------------------------------------------------------------------------

def test_серия_одной_буквы_это_петля_а_не_слово():
    assert kinds(dg.scan_text("и дальше " + "И" * 12 + " конец")) == {"char"}
    assert dg.scan_text("и дальше " + "И" * 12)[0].n == 12


def test_ряд_знаков_ловится_а_многоточие_нет():
    assert kinds(dg.scan_text("ура!!!!!!!!")) == {"punct"}
    assert dg.scan_text("и тут… вот так... дальше") == [], "многоточие — это речь, а не порча"
    assert dg.scan_text("Ура!!! Здорово!!!") == [], "три знака — это выразительность"


def test_повтор_подстроки_внутри_слова():
    spans = dg.scan_text("сказал СловоСловоСлово потом")
    assert kinds(spans) == {"token"} and spans[0].n == 3


def test_слово_повторённое_восемь_раз_речью_не_бывает():
    assert kinds(dg.scan_text("а " * 9)) == {"word"}
    assert kinds(dg.scan_text("нет, " * 8)) == {"word"}


def test_три_повтора_растянутые_во_времени():
    """«Кузнецова Кузнецова Кузнецова» за две секунды — речь; за двадцать — петля."""
    speech = dg.scan_words([turn(["Кузнецова", "Кузнецова", "Кузнецова"], step=0.5)])
    assert speech == [], "полторы секунды — обычный повтор в речи"

    loop = dg.scan_words([turn(["Кузнецова", "Кузнецова", "Кузнецова"], step=7.0)])
    assert "run" in kinds(loop) and [s for s in loop if s.kind == "run"][0].sec >= dg.RUN_SEC


def test_слово_в_двадцать_секунд_это_потерянная_речь():
    spans = dg.scan_words([{"words": [["Здравствуйте.", 10.0, 32.0]]}])
    assert kinds(spans) == {"long"}
    assert spans[0].sec == 22.0 and spans[0].t0 == 10.0


def test_словарная_форма_слова_тоже_понимается():
    """Пословный сайдкар бывает и словарём — детектор обязан читать обе формы."""
    spans = dg.scan_words([{"words": [{"w": "Здравствуйте.", "t0": 1.0, "t1": 25.0}]}])
    assert kinds(spans) == {"long"}


# --- что НЕ ловится --------------------------------------------------------------------------

def test_живая_речь_детектор_не_трогает():
    живое = [
        "да, да, да, понял тебя",
        "Кузнецова, Кузнецова, Кузнецова — это же она и есть",
        "ну что, ааа, вот так вот",
        "оооо, как интересно",
        "чуть-чуть подвинем и всё",
        "Ура!!! Работает.",
    ]
    for line in живое:
        assert dg.scan_text(line) == [], line


def test_семь_букв_ещё_речь_восемь_уже_нет():
    """Порог взят по РАЗРЫВУ в распределении: длины 8 и 9 в корпусе не встречаются вовсе."""
    assert dg.scan_text("ааааааа") == []            # семь
    assert kinds(dg.scan_text("аааааааа")) == {"char"}   # восемь


# --- время спана -----------------------------------------------------------------------------

def test_время_спана_это_время_места_а_не_всей_реплики():
    """⚠️⚠️ Ловилось живьём: признак ищется в слове, а время бралось от реплики — спан выходил
    на 17 минут вместо 25 секунд, и переслушивать такой кусок бессмысленно."""
    long_turn = turn(["слово"] * 200, t0=0.0, step=0.5)          # реплика на 100 секунд
    long_turn["words"][50] = ["И" * 20, 25.0, 29.0]
    spans = [s for s in dg.scan_words([long_turn]) if s.kind == "char"]
    assert len(spans) == 1
    assert spans[0].t0 == 25.0 and spans[0].t1 == 29.0


def test_соседние_находки_сливаются_в_одно_место():
    """Одно и то же место ловится двумя формами; переслушивать его надо ОДИН раз."""
    spans = dg.scan_words([{"words": [["И" * 12, 10.0, 18.0], ["Привет.", 18.2, 40.0]]}])
    # Место ловится сразу двумя формами: это и петля, и растянутое на восемь секунд слово.
    assert kinds(spans) == {"char", "long"} and len(spans) == 3
    merged = dg.merge(spans)
    assert len(merged) == 1 and merged[0].t0 == 10.0 and merged[0].t1 == 40.0
    assert merged[0].extra["kinds"] == {"char", "long"}


def test_повтор_фразы_без_найденного_начала_остаётся_без_времени():
    """Спан без времени честнее спана, который зовёт переслушать полчаса."""
    spans = dg.scan_words([turn(["не", "знаю"] * 5, step=0.3)])
    phrase = [s for s in spans if s.kind == "phrase"]
    assert phrase and phrase[0].t0 is not None, "начало найдено — время есть"
    assert phrase[0].sec < 10


# --- дыра во времени: речь была, слов нет ----------------------------------------------------

def test_дыра_между_словами_внутри_реплики_это_потерянная_речь():
    """Реплика — непрерывная речь по диаризатору; десять секунд без слов внутри неё речь потеряли."""
    t = turn(["раз", "два"])
    t["words"][1] = ["два", 12.0, 12.4]
    t["start"], t["end"] = 0.0, 12.4
    holes = dg.scan_holes([t])
    assert [h.kind for h in holes] == ["hole"]
    assert (holes[0].t0, holes[0].t1) == (0.4, 12.0)


def test_дыра_между_репликами_законна():
    """Между репликами диаризатор речи и не слышал — молчание там не дефект, а пауза."""
    a = turn(["раз"], t0=0.0)
    a["start"], a["end"] = 0.0, 0.4
    b = turn(["два"], t0=30.0)
    b["start"], b["end"] = 30.0, 30.4
    assert dg.scan_holes([a, b]) == []


def test_дыра_на_краю_реплики_тоже_считается():
    """⚠️ Главный подслучай: слов между границей реплики и первым словом нет вовсе, и без этой
    проверки треть находок невидима — ловилось на записи, где речь пропала в НАЧАЛЕ реплики."""
    t = turn(["поехали"], t0=20.0)
    t["start"], t["end"] = 10.0, 20.4
    holes = dg.scan_holes([t])
    assert [(h.t0, h.t1) for h in holes] == [(10.0, 20.0)]

    t2 = turn(["всё"], t0=10.0)
    t2["start"], t2["end"] = 10.0, 25.0
    assert [(h.t0, h.t1) for h in dg.scan_holes([t2])] == [(10.4, 25.0)]


def test_короткая_пауза_дырой_не_считается():
    t = turn(["раз", "два"])
    t["words"][1] = ["два", 5.0, 5.4]          # пять секунд — ещё пауза, не потеря
    t["start"], t["end"] = 0.0, 5.4
    assert dg.scan_holes([t]) == []


def test_реплика_без_слов_не_дыра():
    """Пустая реплика — это запись без слов, а не потерянная речь: делить нечего."""
    assert dg.scan_holes([{"words": [], "start": 0.0, "end": 60.0}]) == []
